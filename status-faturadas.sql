SELECT
FAT.CODIGO,
FAT.TIPOFATURAMENTO,

EMP.NOMEFANTASIA AS 'EMPRESA',
CLI.APELIDO AS 'APELIDO CLIENTE',
(SELECT (CASE K_PONTOATENDIMENTO WHEN 35 THEN 'REEMBOLSO'WHEN 36 THEN 'AUDITORIA'WHEN 33 THEN 'POSTO EMBRAPA'WHEN 27 THEN 'POSTO ITAIPU'
                                WHEN 30 THEN 'POSTO BB' WHEN 3 THEN 'CAIXA' WHEN 4 THEN 'CAIXA BH' WHEN 19 THEN 'POSTO PETROBRAS'
                                WHEN 26 THEN 'POSTO PETROBRAS' WHEN 20 THEN 'POSTO GDF' WHEN 17 THEN 'POSTO MPDG E DERIVADOS'
                                WHEN 28 THEN 'POSTO MPDG E DERIVADOS' WHEN 29 THEN 'POSTO MPDG E DERIVADOS' WHEN 31 THEN 'POSTO MPDG E DERIVADOS'
                                WHEN 32 THEN 'POSTO MPDG E DERIVADOS' WHEN 34 THEN 'POSTO MPDG E DERIVADOS' WHEN 23 THEN 'POSTO BNDES'
                                WHEN 24 THEN 'POSTO FURNAS' ELSE 'DEMAIS CLIENTES' END) from BennerSistemaCorporativo.dbo.GN_PESSOAS WHERE HANDLE = CLI.HANDLE) AS 'PONTO_ATENDIMENTO',
CASE
WHEN FAT.STATUS = 1 THEN 'NOVA'
WHEN FAT.STATUS = 2 THEN 'CADASTRADA'
WHEN FAT.STATUS = 3 THEN 'GERADA'
WHEN FAT.STATUS = 4 THEN 'EMITIDA'
WHEN FAT.STATUS = 5 THEN 'CANCELADA'
WHEN FAT.STATUS = 6 THEN 'LIQUIDADA'
END AS  'STATUS',
CONVERT(VARCHAR(12),FAT.DATA,103) AS 'DATA EMISSAO',
CONVERT(VARCHAR(12),FAT.DATACONFIRMACAO,103) AS 'DATA CONFIRMACAO',
CONVERT(VARCHAR(12),PAR.VCTOPRORROGADO,103) AS 'VENCTO PRORROGADO',
CONVERT(VARCHAR(12),PAR.DATALIQUIDACAO,103) AS 'DATA LIQUIDACAO',
PAR.VALOR AS 'VAL. LIQUIDO',
PAR.VALORESBAIXADOS AS 'VALOR BAIXADO',
(SELECT NOME from BennerSistemaCorporativo.dbo.Z_GRUPOUSUARIOS USU WHERE USU.HANDLE = FAT.CONFIRMADOPOR) AS 'NOME FATURISTA'
from BennerSistemaCorporativo.dbo.BB_FATURAS FAT
INNER join BennerSistemaCorporativo.dbo.FILIAIS FIL ON FIL.HANDLE = FAT.FILIAL
INNER join BennerSistemaCorporativo.dbo.EMPRESAS EMP ON EMP.HANDLE = FIL.EMPRESA
INNER join BennerSistemaCorporativo.dbo.GN_PESSOAS CLI ON CLI.HANDLE = FAT.CLIENTE
INNER join BennerSistemaCorporativo.dbo.FN_DOCUMENTOS DOC ON DOC.HANDLE = FAT.DOCUMENTOFATURA
INNER join BennerSistemaCorporativo.dbo.FN_PARCELAS PAR ON  PAR.DOCUMENTO = DOC.HANDLE
WHERE
EMP.HANDLE IN ('3','7')
--AND FAT.STATUS = '3'
